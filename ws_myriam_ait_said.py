# Extracting useful features for NER
# The CRF model needs features to learn patterns in text.
def word_features(sentence, index):
    word = sentence["tokens"][index]

    features = {
        "word.lower()": word.lower(),  # Lowercased word
        "word.isupper()": word.isupper(),  # Checks if the word is fully uppercase
        "word.istitle()": word.istitle(),  # Checks if the word starts with an uppercase letter
        "word.isdigit()": word.isdigit(),  # Checks if the word is a number
    }

    # Contextual Features: Adding information about surrounding words
    if index > 0:
        features["prev_word.lower()"] = sentence["tokens"][index - 1].lower()
    else:
        features["BOS"] = True  # Beginning of sentence marker

    if index < len(sentence["tokens"]) - 1:
        features["next_word.lower()"] = sentence["tokens"][index + 1].lower()
    else:
        features["EOS"] = True  # End of sentence marker

    return features

