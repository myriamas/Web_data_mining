def clean_uri(entity):
    entity = unidecode(entity.lower().strip())
    entity = re.sub(r'[^\w]+', '_', entity)   # remplace tout groupe non alphanumérique par un _
    return entity.strip('_')

def clean_text(text):
    text = re.sub(r'\s+', ' ', text)
    text = re.sub(r'[^\w\s\-]', '', text)
    text = text.lower()
    tokens = word_tokenize(text)
    return " ".join([t for t in tokens if t not in stopwords.words('english')])

# Named Entity Recognition
def extract_entities(text):
    doc = nlp(text)
    return [(ent.text, ent.label_) for ent in doc.ents]

# Relation Extraction: subject-verb-object triplets
def extract_relations(text):
    doc = nlp(text)
    triples = []

    for sent in doc.sents:
        for token in sent:
            # X is a Y
            if token.dep_ == "nsubj" and token.head.lemma_ == "be":
                subject = token.text
                for child in token.head.children:
                    if child.dep_ == "attr" or child.dep_ == "acomp":
                        obj = child.text
                        triples.append((subject, "is_a", obj))

            # X named Y
            if token.dep_ == "nsubjpass" and token.head.lemma_ == "name":
                subject = token.text
                for child in token.head.children:
                    if child.dep_ == "agent":
                        for obj in child.children:
                            if obj.dep_ == "pobj":
                                triples.append((obj.text, "named", subject))

            # X's Y (possessive)
            if token.dep_ == "poss":
                possessor = token.text
                for child in token.head.children:
                    if child.dep_ == "attr":
                        triples.append((possessor, token.head.lemma_, child.text))

    return triples
