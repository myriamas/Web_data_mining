def predict_tail_entities(result, head_label, relation_label, k=5):
    model = result.model
    triples_factory = result.training

    entity_to_id = triples_factory.entity_to_id
    relation_to_id = triples_factory.relation_to_id
    id_to_entity = {v: k for k, v in entity_to_id.items()}

    if head_label not in entity_to_id or relation_label not in relation_to_id:
        raise ValueError("Head or relation label not found.")

    head_id = entity_to_id[head_label]
    relation_id = relation_to_id[relation_label]

    # Create tensor for (head, relation)
    head_relation_batch = torch.tensor([[head_id, relation_id]])

    # Score all possible tails
    scores = model.score_t(head_relation_batch)

    # Get top-k
    top_scores, top_indices = torch.topk(scores, k=k, dim=1)

    return [(id_to_entity[idx.item()], top_scores[0, i].item()) for i, idx in enumerate(top_indices[0])]

