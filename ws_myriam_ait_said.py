def evaluate_spacy(nlp, dataset):
    y_true, y_pred = [], []

    ner_label_map = dataset.features["ner_tags"].feature
    valid_labels = set(ner_label_map.names)
    texts = [" ".join(sentence["tokens"]) for sentence in dataset]
    true_tags_list = [[ner_label_map.int2str(tag) for tag in sentence["ner_tags"]] for sentence in dataset]
    tokens_list = [sentence["tokens"] for sentence in dataset]
    docs = list(nlp.pipe(texts, batch_size=16))
    for tokens, true_tags, doc in zip(tokens_list, true_tags_list, docs):
        pred_tags = ["O"] * len(tokens)

        for ent in doc.ents:
            ent_tokens = ent.text.split()
            for i, token in enumerate(tokens):
                if token in ent_tokens:
                    tag = f"B-{ent.label_}" if i == 0 else f"I-{ent.label_}"
                    if tag in valid_labels:
                        pred_tags[i] = tag

        y_true.append(true_tags)
        y_pred.append(pred_tags)

    return y_true, y_pred

def compute_scores(y_true, y_pred, zero_division=0):
    y_true_flat = [tag for sent in y_true for tag in sent]
    y_pred_flat = [tag for sent in y_pred for tag in sent]

    # Labels présents dans le dataset (sauf 'O' si tu veux l'exclure)
    all_labels = sorted(list(set(y_true_flat)))

    precision = precision_score(y_true_flat, y_pred_flat, average='weighted', labels=all_labels, zero_division=zero_division)
    recall = recall_score(y_true_flat, y_pred_flat, average='weighted', labels=all_labels, zero_division=zero_division)
    f1 = f1_score(y_true_flat, y_pred_flat, average='weighted', labels=all_labels, zero_division=zero_division)

    return precision, recall, f1

