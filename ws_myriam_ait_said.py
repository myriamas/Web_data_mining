# Web scraping articles from NPR
def fetch_npr_articles():
    url = "https://www.npr.org/sections/world/"
    response = requests.get(url)
    soup = BeautifulSoup(response.content, "html.parser")
    articles = []

    for link in soup.select('article h2 a')[:10]:
        try:
            title = link.get_text(strip=True)
            article_url = link['href']
            article_response = requests.get(article_url)
            article_soup = BeautifulSoup(article_response.content, 'html.parser')

            # Try multiple ways to extract article text
            paragraphs = article_soup.select('article p')
            if not paragraphs:
                paragraphs = article_soup.select('div[class*="article"] p')
            if not paragraphs:
                paragraphs = article_soup.find_all('p')  # fallback

            content = " ".join([p.get_text(strip=True) for p in paragraphs])
            articles.append({'title': title, 'url': article_url, 'content': content})
        except Exception as e:
            print("Article error:", e)
            continue
    return articles

